#!/usr/bin/env python3
"""Build QuartzInk's 1-bit images for FreeInkUI's BitmapFormat::BW1.

src/images/QuartzLogo.h: the gem logo and "Quartz Ink" wordmark cropped from
assets/quartzink/logo.jpg (the default sleep screen draws it).

src/images/QuartzBoot.h: the full-screen boot art, assets/quartzink/boot.jpg
(480x800). The X3/X4 build gets a 528x800 copy scaled to cover the X3's
528x792 panel, which each device crops from the center; the 480x800 boards
get the art at its own size.

Both are Floyd-Steinberg dithered, set bit = ink, MSB first.
"""

from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "quartzink" / "logo.jpg"
OUTPUT = ROOT / "src" / "images" / "QuartzLogo.h"
BOOT_SOURCE = ROOT / "assets" / "quartzink" / "boot.jpg"
BOOT_OUTPUT = ROOT / "src" / "images" / "QuartzBoot.h"
X3_WIDTH = 528
WORDMARK_BOTTOM = 520  # everything above this line is the logo + wordmark
PADDING = 2


def main() -> None:
    gray = ImageOps.grayscale(Image.open(SOURCE))
    top = gray.crop((0, 0, gray.width, WORDMARK_BOTTOM))
    ink = top.point(lambda v: 255 if v < 235 else 0)
    left, upper, right, lower = ink.getbbox()
    box = (max(0, left - PADDING), max(0, upper - PADDING), min(top.width, right + PADDING), min(top.height, lower + PADDING))
    logo = top.crop(box)
    mono = logo.convert("1")  # Floyd-Steinberg dither; 0 = black
    width, height = mono.size
    row_bytes = (width + 7) // 8
    data = bytearray(row_bytes * height)
    pixels = mono.load()
    for y in range(height):
        for x in range(width):
            if pixels[x, y] == 0:
                data[y * row_bytes + x // 8] |= 0x80 >> (x % 8)

    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_quartz_logo.py from assets/quartzink/logo.jpg. Do not edit.",
        "// QuartzInk gem logo and wordmark: 1-bit, set bit = ink, MSB first (FreeInkUI BW1).",
        f"constexpr uint16_t QUARTZ_LOGO_WIDTH = {width};",
        f"constexpr uint16_t QUARTZ_LOGO_HEIGHT = {height};",
        "static const uint8_t QuartzLogo[] = {",
    ]
    for i in range(0, len(data), 19):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 19]) + ",")
    lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n")
    mono.save(ROOT / ".pio" / "quartz_logo_preview.png") if (ROOT / ".pio").exists() else None
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {width}x{height}, {len(data)} bytes")


def pack(mono: Image.Image) -> bytes:
    width, height = mono.size
    row_bytes = (width + 7) // 8
    data = bytearray(row_bytes * height)
    pixels = mono.load()
    for y in range(height):
        for x in range(width):
            if pixels[x, y] == 0:
                data[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(data)


def array_lines(name: str, data: bytes) -> list:
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 19):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 19]) + ",")
    lines.append("};")
    return lines


def boot() -> None:
    gray = ImageOps.grayscale(Image.open(BOOT_SOURCE))
    native = gray.convert("1")
    # Cover the X3: scale to its width, then trim the extra height evenly.
    scaled_h = round(gray.height * X3_WIDTH / gray.width)
    trim = (scaled_h - gray.height) // 2
    x3 = gray.resize((X3_WIDTH, scaled_h), Image.LANCZOS).crop((0, trim, X3_WIDTH, trim + gray.height)).convert("1")
    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_quartz_logo.py from assets/quartzink/boot.jpg. Do not edit.",
        "// QuartzInk boot art: 1-bit, set bit = ink, MSB first (FreeInkUI BW1). Drawn with",
        "// BitmapMode::Cover, so it fills any panel and is cropped from the center.",
        "#if FREEINK_DEVICE_X3",
        f"constexpr uint16_t QUARTZ_BOOT_WIDTH = {x3.width};",
        f"constexpr uint16_t QUARTZ_BOOT_HEIGHT = {x3.height};",
        *array_lines("QuartzBoot", pack(x3)),
        "#else",
        f"constexpr uint16_t QUARTZ_BOOT_WIDTH = {native.width};",
        f"constexpr uint16_t QUARTZ_BOOT_HEIGHT = {native.height};",
        *array_lines("QuartzBoot", pack(native)),
        "#endif",
    ]
    BOOT_OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {BOOT_OUTPUT.relative_to(ROOT)}: {native.width}x{native.height} and {x3.width}x{x3.height}")


if __name__ == "__main__":
    main()
    boot()
